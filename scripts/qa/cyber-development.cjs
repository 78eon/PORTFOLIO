const { chromium } = require('playwright')
const fs = require('node:fs')
;(async () => {
  const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader', '--use-angle=swiftshader'] })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage(), errors = [], checks = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://localhost:3001/')
  await page.getByRole('button', { name: 'Decline', exact: true }).click()
  await page.locator('#cyber-explorer').scrollIntoViewIfNeeded()
  await page.locator('.cyber-map-mode').filter({ hasText: 'Interactive 3D' }).waitFor()
  checks.push({ name: 'Strict Mode initialization owns exactly one canvas', passed: await page.locator('.cyber-scene canvas').count() === 1 })
  await page.getByRole('button', { name: 'Use static map', exact: true }).click()
  await page.getByRole('button', { name: 'Explore in 3D', exact: true }).click()
  await page.locator('.cyber-map-mode').filter({ hasText: 'Interactive 3D' }).waitFor()
  checks.push({ name: 'Strict Mode remount owns a fresh working canvas', passed: await page.locator('.cyber-scene canvas').count() === 1 })
  checks.push({ name: 'Development has no hydration or runtime exceptions', passed: errors.length === 0 })
  fs.writeFileSync('docs/qa/webgl/development.json', JSON.stringify({ checks, errors }, null, 2))
  await browser.close()
  console.log(checks)
  if (checks.some(check => !check.passed)) process.exit(1)
})().catch(error => { console.error(error); process.exit(1) })
